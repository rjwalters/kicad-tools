"""Board 04 stays 9/9 when its placement is spread uniformly to 2x (#6307).

Completion must not drop when a router is given more room: ``auto_pcb_size``
grows the envelope on failure assuming more room cannot hurt.  At the time
#6307 was filed, the 120 x 80 mm spread (``scale_board_tree`` uniform 2.0,
pinned 0.05 mm grid) lost net ``SWO`` to a via-vs-foreign-segment violation
with ``NRST`` and a failed double recovery ("Demoted 1 net(s) with cross-net
shorting copper").  The 1x and rigid-cluster rows were 9/9.

On current main the 2x board routes 9/9 with 0 ``kct check`` and 0 kicad-cli
DRC errors; this test pins that.  See docs/research/expand-route-shrink-experiment.md.
Runs the harness's own protocol (the scaled board is generated by
``scale_board_tree`` inside the harness).  ~45 s, so ``slow`` only.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
HARNESS = REPO / "scripts" / "research" / "expand_route_experiment.py"
ROUTE_TIMEOUT_S = 600
SUBPROCESS_GRACE_S = 240

pytestmark = [pytest.mark.slow]


def test_board04_uniform_2x_routes_all_signal_nets(tmp_path):
    rows_path = tmp_path / "rows.json"
    cmd = [
        sys.executable, str(HARNESS), "route",
        "--boards", "04",
        "--grid-policy", "pinned", "--grid-mm", "0.05",
        "--scales", "2.0", "--modes", "uniform",
        "--seed", "42",
        "--timeout", str(ROUTE_TIMEOUT_S),
        "--work-dir", str(tmp_path / "work"),
        "--json", str(rows_path),
    ]  # fmt: skip
    proc = subprocess.run(
        cmd,
        cwd=REPO,
        capture_output=True,
        text=True,
        timeout=ROUTE_TIMEOUT_S + SUBPROCESS_GRACE_S,
    )
    assert proc.returncode == 0, proc.stdout[-4000:] + proc.stderr[-4000:]
    rows = json.loads(rows_path.read_text())["rows"]
    assert len(rows) == 1, rows
    row = rows[0]
    assert row["scale_report"]["outline_mm"] == [120.0, 80.0]
    summary = {k: row.get(k) for k in ("router_nets", "signal_nets_unfinished", "vias_by_net")}
    assert row.get("router_nets") == "9/9", summary
    assert row.get("signal_nets_unfinished") == 0, summary
    assert row.get("kct_check_errors") == 0, summary
    assert row.get("kicad_drc_errors") == 0, summary
    assert row.get("artifact") == "final", summary
