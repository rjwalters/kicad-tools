"""Golden-fixture tests pinning the mirror strategy to KiCad's own flip (#4560).

``tests/fixtures/mirror_flip/`` holds a committed pair generated by KiCad
10.0.6 itself (see ``generate_golden.py`` there):

* ``mirror_front.kicad_pcb``  -- one asymmetric footprint ``U1`` on ``F.Cu``
  at rotation 30 (mixed SMD/through-hole pads, non-axis pad angles);
* ``mirror_back_lr.kicad_pcb`` -- the SAME board after KiCad's
  ``FOOTPRINT.Flip(anchor, FLIP_DIRECTION_LEFT_RIGHT)``.

These tests assert that ``StrategyApplicator``'s ``MIRROR_COMPONENT`` turns
the front board into the back board -- absolute pad geometry (positions,
layer lists, angles), footprint layer/position/rotation -- and that the
mutation *serializes* (flip -> save -> reparse shows the flip; the
``Pad.__setattr__`` write-through hazard from the issue).  KiCad is NOT
required at test time; the ``kicad-cli pcb drc`` cross-gate below skips when
the binary is absent (as on the plain CI test runner).

The empirically-pinned file-level transform (30 deg was chosen because it is
NOT a fixed point of the candidate transforms, which 90/270 are):

* footprint layer ``F.* <-> B.*``; rotation ``theta -> 180 - theta``;
* pad local position ``(x, y) -> (x, -y)`` (constant in theta);
* pad ABSOLUTE angle ``a -> 180 - a`` (the left/right reflection of an
  orientation -- NOT ``-a``, which is the top/bottom flip);
* pad layers side-swapped per name (through-hole ``*.Cu``/``*.Mask``
  unchanged).
"""

from __future__ import annotations

import json
import math
import subprocess
from pathlib import Path

import pytest

from kicad_tools.cli.runner import find_kicad_cli
from kicad_tools.recovery import (
    Action,
    Difficulty,
    ResolutionStrategy,
    StrategyApplicator,
    StrategyType,
)
from kicad_tools.schema.pcb import PCB

_FIXTURES = Path(__file__).resolve().parent / "fixtures" / "mirror_flip"
_FRONT = _FIXTURES / "mirror_front.kicad_pcb"
_BACK = _FIXTURES / "mirror_back_lr.kicad_pcb"

# KiCad stores coordinates in integer nanometres; its own flip leaves ~1e-6 mm
# artifacts, and our serializer's float formatting is 6 significant digits.
_TOL = 1e-4


def _u1(pcb: PCB):
    return next(fp for fp in pcb.footprints if fp.reference == "U1")


def _mirror_strategy(ref: str = "U1") -> ResolutionStrategy:
    return ResolutionStrategy(
        type=StrategyType.MIRROR_COMPONENT,
        difficulty=Difficulty.MEDIUM,
        confidence=1.0,
        actions=[Action(type="mirror", target=ref, params={})],
    )


def _abs_pad_positions(fp) -> dict[str, tuple[float, float]]:
    """Board-frame pad centres, using the router's local->board convention
    (``router/io.py``: KiCad footprint orientation applies as a negated angle
    vs standard CCW math)."""
    rot = math.radians(-fp.rotation)
    c, s = math.cos(rot), math.sin(rot)
    out: dict[str, tuple[float, float]] = {}
    for pad in fp.pads:
        x, y = pad.position
        out[pad.number] = (
            fp.position[0] + x * c - y * s,
            fp.position[1] + x * s + y * c,
        )
    return out


def _flip_front() -> PCB:
    pcb = PCB.load(str(_FRONT))
    result = StrategyApplicator().apply_strategy(pcb, _mirror_strategy())
    assert result.success is True
    assert result.components_moved == ["U1"]
    return pcb


class TestMirrorMatchesKiCadFlip:
    def test_footprint_layer_position_rotation(self):
        flipped = _u1(_flip_front())
        golden = _u1(PCB.load(str(_BACK)))
        assert flipped.layer == golden.layer == "B.Cu"
        # Flip about the footprint's own anchor keeps the centre fixed.
        assert flipped.position == pytest.approx(golden.position, abs=_TOL)
        assert (flipped.rotation - golden.rotation) % 360.0 == pytest.approx(0.0, abs=_TOL)

    def test_pad_absolute_geometry_equals_golden(self):
        flipped = _u1(_flip_front())
        golden = _u1(PCB.load(str(_BACK)))
        assert [p.number for p in flipped.pads] == [p.number for p in golden.pads]

        flipped_abs = _abs_pad_positions(flipped)
        golden_abs = _abs_pad_positions(golden)
        for mine, theirs in zip(flipped.pads, golden.pads, strict=True):
            # Absolute board-frame centre.
            assert flipped_abs[mine.number] == pytest.approx(golden_abs[theirs.number], abs=_TOL), (
                f"pad {mine.number} absolute position"
            )
            # Local file coordinates too (the transform is (x, -y)).
            assert mine.position == pytest.approx(theirs.position, abs=_TOL)
            # Absolute angle, mod 360 (KiCad normalizes to (-180, 180]).
            assert (mine.rotation - theirs.rotation) % 360.0 == pytest.approx(0.0, abs=_TOL), (
                f"pad {mine.number} angle"
            )
            # Layer lists swap side per name; through-hole stays *.Cu/*.Mask.
            assert mine.layers == theirs.layers, f"pad {mine.number} layers"

    def test_through_hole_pad_layers_unchanged(self):
        front = PCB.load(str(_FRONT))
        pth_before = next(p for p in _u1(front).pads if p.number == "4")
        assert pth_before.layers == ["*.Cu", "*.Mask"]
        flipped = _u1(_flip_front())
        pth = next(p for p in flipped.pads if p.number == "4")
        assert pth.layers == ["*.Cu", "*.Mask"]

    def test_cosmetics_moved_to_back_side(self):
        flipped = _u1(_flip_front())
        golden = _u1(PCB.load(str(_BACK)))
        assert {t.layer for t in flipped.texts} == {t.layer for t in golden.texts}
        assert all(t.layer.startswith("B.") for t in flipped.texts)
        silk_mine = [g for g in flipped.graphics if g.layer == "B.SilkS"]
        silk_gold = [g for g in golden.graphics if g.layer == "B.SilkS"]
        assert len(silk_mine) == len(silk_gold) == 1
        assert silk_mine[0].start == pytest.approx(silk_gold[0].start, abs=_TOL)
        assert silk_mine[0].end == pytest.approx(silk_gold[0].end, abs=_TOL)

    def test_double_flip_is_identity(self):
        pcb = PCB.load(str(_FRONT))
        original = _u1(PCB.load(str(_FRONT)))
        applicator = StrategyApplicator()
        applicator.apply_strategy(pcb, _mirror_strategy())
        applicator.apply_strategy(pcb, _mirror_strategy())
        fp = _u1(pcb)
        assert fp.layer == original.layer
        assert (fp.rotation - original.rotation) % 360.0 == pytest.approx(0.0, abs=_TOL)
        for mine, theirs in zip(fp.pads, original.pads, strict=True):
            assert mine.position == pytest.approx(theirs.position, abs=_TOL)
            assert (mine.rotation - theirs.rotation) % 360.0 == pytest.approx(0.0, abs=_TOL)
            assert mine.layers == theirs.layers


class TestMirrorSerializes:
    """The flip must reach the S-expression tree ``PCB.save`` writes -- the
    ``Pad.__setattr__`` rotation-only write-through hazard from #4560."""

    def test_flip_save_reparse_shows_the_flip(self, tmp_path: Path):
        pcb = _flip_front()
        out = tmp_path / "flipped.kicad_pcb"
        pcb.save(str(out))

        reloaded = _u1(PCB.load(str(out)))
        golden = _u1(PCB.load(str(_BACK)))
        assert reloaded.layer == "B.Cu"
        assert (reloaded.rotation - golden.rotation) % 360.0 == pytest.approx(0.0, abs=_TOL)
        for mine, theirs in zip(reloaded.pads, golden.pads, strict=True):
            assert mine.position == pytest.approx(theirs.position, abs=_TOL)
            assert (mine.rotation - theirs.rotation) % 360.0 == pytest.approx(0.0, abs=_TOL)
            assert mine.layers == theirs.layers
        # Cosmetic children followed to the back side in the file too, with
        # the y-negation applied -- layer names alone would not catch a
        # side-swap that forgot the geometry (the board's layer-definition
        # table legitimately still names F.SilkS, so assert on ``(layer ...)``
        # references only).
        text = out.read_text()
        assert '(layer "F.SilkS")' not in text
        assert '(layer "B.SilkS")' in text
        silk_reloaded = [g for g in reloaded.graphics if g.layer == "B.SilkS"]
        silk_golden = [g for g in golden.graphics if g.layer == "B.SilkS"]
        assert len(silk_reloaded) == len(silk_golden) == 1
        assert silk_reloaded[0].start == pytest.approx(silk_golden[0].start, abs=_TOL)
        assert silk_reloaded[0].end == pytest.approx(silk_golden[0].end, abs=_TOL)
        # The transform is a y-negation of the ORIGINAL local coordinates.
        front_silk = next(g for g in _u1(PCB.load(str(_FRONT))).graphics if g.layer == "F.SilkS")
        assert silk_reloaded[0].start == pytest.approx(
            (front_silk.start[0], -front_silk.start[1]), abs=_TOL
        )

    @pytest.mark.skipif(
        find_kicad_cli() is None,
        reason="find_kicad_cli() found no kicad-cli install (checked PATH and common install locations)",
    )
    def test_kicad_cli_drc_cross_gate(self, tmp_path: Path):
        """Repo process rule: ``kct check`` alone is insufficient -- the saved
        flipped board must load and DRC clean in KiCad's own tooling."""
        pcb = _flip_front()
        out = tmp_path / "flipped.kicad_pcb"
        pcb.save(str(out))
        report = tmp_path / "drc.json"
        proc = subprocess.run(
            [
                str(find_kicad_cli()),
                "pcb",
                "drc",
                "--severity-error",
                "--exit-code-violations",
                "--format",
                "json",
                "-o",
                str(report),
                str(out),
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )
        assert proc.returncode == 0, f"kicad-cli drc failed:\n{proc.stdout}\n{proc.stderr}"
        payload = json.loads(report.read_text())
        assert payload.get("violations", []) == []


class TestJustifyResidue:
    """The ``(justify mirror)`` toggle must not litter the file (#4736).

    A double flip creates ``(justify mirror)`` from nothing and then empties
    it again; the empty ``(justify)`` shell must be dropped so flip-flip
    round-trips the text effects to their original byte shape.
    """

    def test_double_flip_leaves_no_empty_justify(self, tmp_path: Path):
        pcb = PCB.load(str(_FRONT))
        applicator = StrategyApplicator()
        applicator.apply_strategy(pcb, _mirror_strategy())
        applicator.apply_strategy(pcb, _mirror_strategy())
        out = tmp_path / "double_flipped.kicad_pcb"
        pcb.save(str(out))
        text = out.read_text()
        assert "(justify)" not in text
        # The front fixture carries no (justify ...) nodes at all, so a
        # flip-flip must not invent any.
        assert "(justify" not in text

    def test_unmirror_preserves_other_justify_tokens(self):
        """Pre-existing ``(justify left mirror)`` un-mirrors to
        ``(justify left)`` -- the node survives when non-mirror tokens
        remain."""
        from kicad_tools.sexp import parse_string

        node = parse_string(
            '(fp_text user "X" (at 0 0) (layer "F.SilkS") '
            "(effects (font (size 1 1) (thickness 0.15)) (justify left mirror)))"
        )
        StrategyApplicator._mirror_cosmetic_node(node)
        effects = node.find_child("effects")
        assert effects is not None
        justify = effects.find_child("justify")
        assert justify is not None, "non-empty justify node must survive un-mirroring"
        assert justify.values == ["left"]


def _custom_pad(fp, number: str = "5"):
    return next(p for p in fp.pads if p.number == number)


def _primitive_points(pad) -> list[float]:
    """Flat ``[x0, y0, x1, y1, ...]`` of every ``(xy x y)`` under the pad's
    ``(primitives ...)`` source node (flat so ``pytest.approx`` can compare)."""
    primitives = pad._sexp_node.find_child("primitives")
    assert primitives is not None
    pts: list[float] = []

    def walk(node) -> None:
        for child in node.iter_children():
            if child.tag == "xy":
                pts.extend((child.get_float(0), child.get_float(1)))
            else:
                walk(child)

    walk(primitives)
    return pts


class TestMirrorCustomPadPrimitives:
    """Issue #9530: a custom pad's ``(primitives ...)`` live only in its source
    node, so the pad-attribute write-through never reached them.  Pad 5 of the
    golden pair is an L-shaped ``gr_poly`` that is NOT symmetric about the
    pad's x axis, so a missing y-mirror changes the copper."""

    def test_primitive_points_equal_kicad_flip(self):
        flipped = _custom_pad(_u1(_flip_front()))
        golden = _custom_pad(_u1(PCB.load(str(_BACK))))
        mine = _primitive_points(flipped)
        theirs = _primitive_points(golden)
        assert len(mine) == len(theirs) == 12
        assert mine == pytest.approx(theirs, abs=_TOL)

    def test_primitive_points_are_y_negated_originals(self):
        original = _primitive_points(_custom_pad(_u1(PCB.load(str(_FRONT)))))
        # The fixture really is asymmetric: negating y changes the point set.
        negated = [v if i % 2 == 0 else -v for i, v in enumerate(original)]
        pairs = lambda flat: sorted(zip(flat[::2], flat[1::2], strict=True))  # noqa: E731
        assert pairs(original) != pairs(negated)
        flipped = _primitive_points(_custom_pad(_u1(_flip_front())))
        assert flipped == pytest.approx(negated, abs=_TOL)

    def test_double_mirror_restores_primitives(self):
        original = _primitive_points(_custom_pad(_u1(PCB.load(str(_FRONT)))))
        pcb = PCB.load(str(_FRONT))
        applicator = StrategyApplicator()
        applicator.apply_strategy(pcb, _mirror_strategy())
        applicator.apply_strategy(pcb, _mirror_strategy())
        restored = _primitive_points(_custom_pad(_u1(pcb)))
        assert restored == pytest.approx(original, abs=_TOL)

    def test_primitives_survive_save_and_reparse(self, tmp_path: Path):
        out = tmp_path / "flipped.kicad_pcb"
        _flip_front().save(str(out))
        reloaded = _custom_pad(_u1(PCB.load(str(out))))
        golden = _custom_pad(_u1(PCB.load(str(_BACK))))
        assert _primitive_points(reloaded) == pytest.approx(_primitive_points(golden), abs=_TOL)

    def test_custom_pad_copper_matches_kicad_flipped_geometry(self):
        pytest.importorskip("shapely")
        from kicad_tools.router.fixed_copper import custom_pad_copper

        def copper(fp):
            pad = _custom_pad(fp)
            x, y = _abs_pad_positions(fp)[pad.number]
            return custom_pad_copper(
                pad._sexp_node.to_string(),
                reference=fp.reference,
                pad_number=pad.number,
                x=x,
                y=y,
                rotation=pad.rotation,
                source_net="",
                source_net_id=0,
            ).geometry

        mine = copper(_u1(_flip_front()))
        theirs = copper(_u1(PCB.load(str(_BACK))))
        assert theirs.area > 0
        assert mine.symmetric_difference(theirs).area == pytest.approx(0.0, abs=1e-6)

    def test_pads_without_primitives_and_test_doubles_are_noops(self):
        # Non-custom pads carry no (primitives ...) node and must stay untouched.
        pad = next(p for p in _u1(PCB.load(str(_FRONT))).pads if p.number == "1")
        assert pad._sexp_node.find_child("primitives") is None
        StrategyApplicator._mirror_pad_primitives(pad)
        assert pad._sexp_node.find_child("primitives") is None

        class _Double:  # no ``_sexp_node`` attribute at all
            pass

        StrategyApplicator._mirror_pad_primitives(_Double())


def _primitive_blocks(pad) -> list[tuple[str, list[tuple[str, list[float]]]]]:
    """Every ``(primitives ...)`` block under *pad*, top level and nested in
    ``(padstack (layer ...))``, as ``(owner, [(tag, flat coords), ...])``.

    ``owner`` is the enclosing padstack layer name (``"F.Cu"`` for the
    top-level block).  Each primitive's start/mid/end/center/xy coordinates are
    kept in file order so endpoint order is compared, not just the point set.
    """
    blocks: list[tuple[str, list[tuple[str, list[float]]]]] = []

    def walk(node, owner: str) -> None:
        for child in node.iter_children():
            if child.tag == "primitives":
                prims = []
                for prim in child.iter_children():
                    coords: list[float] = []

                    def collect(n) -> None:
                        for c in n.iter_children():
                            if c.tag in ("start", "mid", "end", "center", "xy"):
                                coords.extend((c.get_float(0), c.get_float(1)))
                            else:
                                collect(c)

                    collect(prim)
                    prims.append((prim.tag, coords))
                blocks.append((owner, prims))
            elif child.tag == "layer" and child.get_string(0):
                walk(child, child.get_string(0))
            else:
                walk(child, owner)

    walk(pad._sexp_node, "F.Cu")
    return blocks


def _assert_blocks_equal(mine, theirs) -> None:
    assert [(o, [t for t, _ in prims]) for o, prims in mine] == [
        (o, [t for t, _ in prims]) for o, prims in theirs
    ]
    for (_, mp), (_, tp) in zip(mine, theirs, strict=True):
        for (_, mc), (_, tc) in zip(mp, tp, strict=True):
            assert mc == pytest.approx(tc, abs=_TOL)


class TestMirrorPadstackPrimitivesAndArcs:
    """Issue #9530 review: pad 6 is a through-hole ``front_inner_back`` custom
    pad with the same asymmetric polygon on F.Cu/In/B.Cu plus a three-point
    ``gr_arc``.  Every layer's nested block must match KiCad 10.0.6's Flip,
    including the arc's reversed endpoint order."""

    def test_fixture_covers_every_layer_and_the_arc(self):
        blocks = _primitive_blocks(_custom_pad(_u1(PCB.load(str(_BACK))), "6"))
        assert len(blocks) == 3, "front, inner and back layers each carry primitives"
        assert any(t == "gr_arc" for _, prims in blocks for t, _ in prims)

    def test_every_layer_block_equals_kicad_flip(self):
        mine = _primitive_blocks(_custom_pad(_u1(_flip_front()), "6"))
        theirs = _primitive_blocks(_custom_pad(_u1(PCB.load(str(_BACK))), "6"))
        _assert_blocks_equal(mine, theirs)

    def test_three_point_arc_endpoints_follow_kicad_order(self):
        blocks = _primitive_blocks(_custom_pad(_u1(_flip_front()), "6"))
        arcs = [c for _, prims in blocks for t, c in prims if t == "gr_arc"]
