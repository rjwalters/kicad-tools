"""
CLI command for initializing KiCad projects with manufacturer design rules.

Provides the `kct init` command to create or configure a KiCad project with
manufacturer-specific design rules from the start, preventing DRC issues later.

Usage:
    kct init myproject --mfr jlcpcb --layers 4
    kct init myproject.kicad_pro --mfr jlcpcb --layers 2
    kct init . --mfr seeed --layers 4 --copper 2
"""

import argparse
import copy
import json
import re
import sys
from pathlib import Path

from rich.console import Console
from rich.table import Table

from kicad_tools.core.netclass_templates import (
    apply_design_template,
    get_available_design_types,
    get_netclass_summary,
)
from kicad_tools.core.rule_loosening import RuleLooseningError, assert_no_loosenings
from kicad_tools.manufacturers import DesignRules, get_manufacturer_ids, get_profile
from kicad_tools.manufacturers.dru_generator import generate_dru, merge_dru_floors
from kicad_tools.manufacturers.project_generator import (
    merge_policy_allowances,
    merge_project_rules_guarded,
)
from kicad_tools.units import get_current_formatter

console = Console()
err_console = Console(stderr=True)


def create_project_file(project_path: Path, project_name: str) -> dict:
    """Create a new KiCad project file with basic structure.

    Args:
        project_path: Path to the project file
        project_name: Name of the project

    Returns:
        Project data dictionary
    """
    return {
        "meta": {"filename": project_name, "version": 1},
        "board": {"design_settings": {"rules": {}, "defaults": {}}},
        "schematic": {"meta": {"version": 1}},
        "sheets": [],
        "text_variables": {},
    }


def create_dru_content(rules: DesignRules, manufacturer_id: str, layers: int) -> str:
    """Generate KiCad design rules file content.

    Args:
        rules: Design rules from manufacturer profile
        manufacturer_id: Manufacturer identifier
        layers: Number of copper layers

    Returns:
        String content for .kicad_dru file
    """
    body = generate_dru(rules, manufacturer_id.upper())
    header = (
        f"# Design rules for {manufacturer_id.upper()} ({layers}-layer)\n"
        "# Generated by kicad-tools init command"
    )
    # NOTE: KiCad DRU comments start with "#"; ";" makes KiCad silently ignore
    # the whole file (Issue #7116).
    # generate_dru() emits "(version 1)" first; keep it first and slot the
    # header comment directly after it.
    version_line, _, rest = body.partition("\n")
    return f"{version_line}\n\n{header}\n\n{rest}"


def update_dru_content(
    existing: str | None,
    rules: DesignRules,
    manufacturer_id: str,
    layers: int,
    *,
    path: Path | None = None,
) -> str:
    """Content for ``kct init``'s ``.kicad_dru``, never dropping foreign rules.

    A missing file, or one that holds only an earlier ``kct init``'s generated
    rules (see :func:`_is_init_generated_dru`), gets :func:`create_dru_content`
    as before.  Anything else -- rules the user wrote, or the other kct
    writers' managed blocks (fab floors, keepouts, creepage, native zone
    clearance) -- is kept verbatim, and the manufacturer floors go into the
    fab-floors managed block instead (Issue #7383; the old blanket overwrite
    deleted them).
    """
    if existing is None or not existing.strip() or _is_init_generated_dru(existing):
        return create_dru_content(rules, manufacturer_id, layers)
    return merge_dru_floors(existing, generate_dru(rules, manufacturer_id.upper()), path=path)


_INIT_HEADER_RE = re.compile(
    r"# Design rules for .+ \(\d+-layer\)|# Generated by kicad-tools init command"
)
_TOP_LEVEL_RULE_RE = re.compile(r'\(rule "((?:[^"\\]|\\.)*)"')


def _is_init_generated_dru(content: str) -> bool:
    """True when ``content`` is exactly what an earlier ``kct init`` wrote.

    That is: a ``(version N)`` line, :func:`create_dru_content`'s two-line
    header, and only top-level rules labelled ``<family> - <MANUFACTURER>``
    for a known manufacturer -- no other comment or top-level form.  A file
    anyone else touched (a hand-written rule, a kct managed block, which
    always starts with a ``# BEGIN`` comment) does not qualify and is merged,
    not replaced.
    """
    suffixes = tuple(f" - {mid.upper()}" for mid in get_manufacturer_ids())
    saw_header = saw_rule = False
    for line in content.splitlines():
        if not line.strip() or line[0].isspace():
            continue
        if _INIT_HEADER_RE.fullmatch(line):
            saw_header = True
            continue
        if re.fullmatch(r"\(version \d+\)", line):
            continue
        rule = _TOP_LEVEL_RULE_RE.match(line)
        if rule is None or not rule.group(1).endswith(suffixes):
            return False
        saw_rule = True
    return saw_header and saw_rule


def create_gitignore_content() -> str:
    """Generate default .gitignore content for KiCad projects.

    Returns:
        String content for .gitignore file
    """
    return """\
# KiCad local settings (per-user, not useful to track)
*.kicad_prl

# Build outputs (regenerated by kct check / kct export)
drc_report.json
manufacturing/
"""


def create_gitignore(project_dir: Path, dry_run: bool = False) -> bool | None:
    """Create a .gitignore file in the project directory if one does not exist.

    Args:
        project_dir: Directory where the .gitignore should be created
        dry_run: If True, do not write the file

    Returns:
        True if the file was created, False if it already existed and was
        skipped, or None if dry_run is True and the file would be created.
    """
    gitignore_path = project_dir / ".gitignore"

    if gitignore_path.exists():
        return False

    if dry_run:
        return None

    gitignore_path.write_text(create_gitignore_content(), encoding="utf-8")
    return True


def print_init_summary(
    project_path: Path,
    dru_path: Path,
    profile,
    rules: DesignRules,
    layers: int,
    copper: float,
    created_project: bool,
    created_dru: bool,
    design_type: str | None = None,
    netclass_summary: list[dict] | None = None,
    gitignore_path: Path | None = None,
    created_gitignore: bool | None = None,
) -> None:
    """Print a summary of what was initialized.

    Args:
        project_path: Path to the project file
        dru_path: Path to the DRU file
        profile: Manufacturer profile
        rules: Design rules applied
        layers: Number of copper layers
        copper: Copper weight in oz
        created_project: Whether a new project was created
        created_dru: Whether DRU file was created/updated
        design_type: Design type template applied (if any)
        netclass_summary: Summary of netclasses created (if any)
        gitignore_path: Path to the .gitignore file
        created_gitignore: Whether the .gitignore was created (True),
            skipped (False), or would be created (None for dry-run)
    """
    fmt = get_current_formatter()
    console.print(f"\n[bold green]✓[/bold green] Initialized project for {profile.name}")
    console.print(f"  Configuration: {layers}-layer, {copper}oz copper")
    if design_type:
        console.print(f"  Design type: {design_type}")
    console.print(f"  Units: {fmt.unit_name}\n")

    # Design rules table
    table = Table(title="Design Rules Applied", show_header=True, header_style="bold cyan")
    table.add_column("Parameter", style="dim")
    table.add_column("Value", justify="right")
    table.add_column("Previous", justify="right", style="dim")

    table.add_row(
        "Via drill",
        fmt.format(rules.min_via_drill_mm),
        fmt.format(0.20) if created_project else "-",
    )
    table.add_row(
        "Via diameter",
        fmt.format(rules.min_via_diameter_mm),
        fmt.format(0.45) if created_project else "-",
    )
    table.add_row(
        "Min clearance",
        fmt.format(rules.min_clearance_mm),
        fmt.format(0.20) if created_project else "-",
    )
    table.add_row(
        "Min trace width",
        fmt.format(rules.min_trace_width_mm),
        fmt.format(0.25) if created_project else "-",
    )
    table.add_row(
        "Annular ring",
        fmt.format(rules.min_annular_ring_mm),
        fmt.format(0.13) if created_project else "-",
    )
    table.add_row(
        "Copper to edge",
        fmt.format(rules.min_copper_to_edge_mm),
        fmt.format(0.30) if created_project else "-",
    )

    console.print(table)

    # Netclass table (if netclasses were configured)
    if netclass_summary and len(netclass_summary) > 1:
        console.print()
        nc_table = Table(title="Net Classes Configured", show_header=True, header_style="bold cyan")
        nc_table.add_column("Class", style="bold")
        nc_table.add_column("Track Width", justify="right")
        nc_table.add_column("Clearance", justify="right")
        nc_table.add_column("Patterns", justify="right", style="dim")

        for nc in netclass_summary:
            nc_table.add_row(
                nc["name"],
                fmt.format(nc["track_width"]),
                fmt.format(nc["clearance"]),
                str(nc["pattern_count"]) if nc["pattern_count"] > 0 else "-",
            )

        console.print(nc_table)

    # Files section
    console.print("\n[bold]Files:[/bold]")
    if created_project:
        console.print(f"  [green]Created:[/green] {project_path}")
    else:
        console.print(f"  [yellow]Updated:[/yellow] {project_path}")

    if created_dru:
        console.print(f"  [green]Created:[/green] {dru_path}")
    else:
        console.print(f"  [yellow]Updated:[/yellow] {dru_path}")

    if gitignore_path is not None:
        if created_gitignore is True or created_gitignore is None:
            console.print(f"  [green]Created:[/green] {gitignore_path}")
        elif created_gitignore is False:
            console.print(f"  [dim]Skipped:[/dim] {gitignore_path} (already exists)")

    # Next steps
    console.print("\n[bold]Next steps:[/bold]")
    console.print("  1. Open project in KiCad")
    console.print("  2. Design schematic")
    console.print("  3. Layout PCB (rules will be enforced)")
    console.print(f"  4. Run: kct audit {project_path.name} --mfr {profile.id}")


def init_project(
    target: str,
    manufacturer: str,
    layers: int = 2,
    copper: float = 1.0,
    design_type: str | None = None,
    dry_run: bool = False,
    output_format: str = "text",
) -> int:
    """Initialize a KiCad project with manufacturer design rules.

    Args:
        target: Project name or path to existing .kicad_pro file
        manufacturer: Manufacturer ID (jlcpcb, seeed, etc.)
        layers: Number of copper layers
        copper: Copper weight in oz
        design_type: Design type template for netclass configuration
        dry_run: If True, show what would be done without making changes
        output_format: Output format ("text" or "json")

    Returns:
        Exit code (0 for success)
    """
    # Get manufacturer profile
    try:
        profile = get_profile(manufacturer)
    except ValueError as e:
        err_console.print(f"[red]Error:[/red] {e}")
        return 1

    # Get design rules for configuration
    rules = profile.get_design_rules(layers, copper)

    # Determine project path
    target_path = Path(target)

    if target_path.suffix == ".kicad_pro":
        # Existing project file specified
        project_path = target_path
        project_name = target_path.stem
    elif target_path.suffix:
        # Some other file extension
        err_console.print(
            f"[red]Error:[/red] Expected .kicad_pro file or project name, got: {target_path.suffix}"
        )
        return 1
    else:
        # Project name/directory specified
        if target == ".":
            # Use current directory name
            project_name = Path.cwd().name
            project_path = Path.cwd() / f"{project_name}.kicad_pro"
        else:
            project_name = target_path.name
            # Add .kicad_pro suffix to the path
            project_path = target_path.with_suffix(".kicad_pro")

    # Determine DRU path (same directory as project file)
    dru_path = project_path.with_suffix(".kicad_dru")

    # Determine gitignore path (same directory as project file)
    gitignore_path = project_path.parent / ".gitignore"

    # Track what we'll create
    will_create_project = not project_path.exists()
    will_create_dru = not dru_path.exists()
    will_create_gitignore = not gitignore_path.exists()

    # JSON output mode
    if output_format == "json":
        result = {
            "project_path": str(project_path),
            "dru_path": str(dru_path),
            "gitignore_path": str(gitignore_path),
            "manufacturer": profile.id,
            "layers": layers,
            "copper_oz": copper,
            "design_type": design_type,
            "rules": rules.to_dict(),
            "will_create_project": will_create_project,
            "will_create_dru": will_create_dru,
            "will_create_gitignore": will_create_gitignore,
            "dry_run": dry_run,
        }
        print(json.dumps(result, indent=2))
        if dry_run:
            return 0

    # Dry run - show what would happen
    if dry_run:
        console.print("\n[bold yellow]Dry run:[/bold yellow] No changes will be made\n")
        print_init_summary(
            project_path,
            dru_path,
            profile,
            rules,
            layers,
            copper,
            will_create_project,
            will_create_dru,
            design_type=design_type,
            gitignore_path=gitignore_path,
            created_gitignore=None if will_create_gitignore else False,
        )
        return 0

    # Create or load project file
    if project_path.exists():
        try:
            project_data = json.loads(project_path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError) as e:
            err_console.print(f"[red]Error:[/red] Failed to load project file: {e}")
            return 1
    else:
        # Create parent directory if needed
        project_path.parent.mkdir(parents=True, exist_ok=True)
        project_data = create_project_file(project_path, project_name)

    # Apply design rules through the one #6191 stricter-wins policy every
    # .kicad_pro writer follows (Issue #7385).  On an existing project an
    # authored minimum or Default-netclass value stricter than the profile
    # is kept; a rewrite that would loosen an authored rule refuses below,
    # before anything is written.
    rules_before = copy.deepcopy(project_data)
    try:
        merge_report = merge_project_rules_guarded(project_data, rules, writer="kct init")
    except RuleLooseningError as e:
        err_console.print(f"Error: {e}", markup=False, highlight=False)
        return 1

    # Store manufacturer metadata
    if "meta" not in project_data:
        project_data["meta"] = {}
    project_data["meta"]["manufacturer"] = profile.id
    project_data["meta"]["layers"] = layers
    project_data["meta"]["copper_oz"] = copper

    # Apply netclass template if specified
    netclass_summary = None
    if design_type:
        try:
            # The Default netclass takes the template's values only where the
            # merge policy already treats it as unauthored (Issue #7385).
            apply_design_template(
                project_data,
                design_type,
                keep_stricter_default=not (
                    {"*", "netclasses.Default.track_width"}
                    & merge_policy_allowances(rules_before, apply_severities=False)
                ),
            )
            project_data["meta"]["design_type"] = design_type
            netclass_summary = get_netclass_summary(project_data)
        except ValueError as e:
            err_console.print(f"[red]Error:[/red] {e}")
            return 1

    # The design template merges stricter-wins too; re-check the complete
    # rewrite against the project as loaded, so neither step can loosen it.
    try:
        assert_no_loosenings(
            rules_before,
            project_data,
            allow=merge_policy_allowances(rules_before, apply_severities=False),
            writer="kct init",
        )
    except RuleLooseningError as e:
        err_console.print(f"Error: {e}", markup=False, highlight=False)
        return 1

    if output_format == "text":
        for line in merge_report.messages():
            console.print(line, markup=False, highlight=False)

    # Write project file
    try:
        project_path.write_text(json.dumps(project_data, indent=2), encoding="utf-8")
    except OSError as e:
        err_console.print(f"[red]Error:[/red] Failed to write project file: {e}")
        return 1

    # Create/update DRU file
    try:
        existing_dru = dru_path.read_text(encoding="utf-8") if dru_path.exists() else None
        dru_content = update_dru_content(existing_dru, rules, profile.id, layers, path=dru_path)
        dru_path.write_text(dru_content, encoding="utf-8")
    except OSError as e:
        err_console.print(f"[red]Error:[/red] Failed to write DRU file: {e}")
        return 1

    # Create .gitignore (only if it doesn't already exist)
    created_gitignore = create_gitignore(project_path.parent)

    # Print summary
    if output_format == "text":
        print_init_summary(
            project_path,
            dru_path,
            profile,
            rules,
            layers,
            copper,
            will_create_project,
            will_create_dru,
            design_type=design_type,
            netclass_summary=netclass_summary,
            gitignore_path=gitignore_path,
            created_gitignore=created_gitignore,
        )

    return 0


def main(argv: list[str] | None = None) -> int:
    """Main entry point for init command."""
    design_types = get_available_design_types()
    parser = argparse.ArgumentParser(
        description="Initialize a KiCad project with manufacturer design rules",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=f"""\
Examples:
  kct init myproject --mfr jlcpcb               Create project with JLCPCB 2-layer rules
  kct init myproject --mfr jlcpcb --layers 4    Create project with 4-layer rules
  kct init myproject --mfr jlcpcb -t audio      Create audio project with netclasses
  kct init existing.kicad_pro --mfr seeed       Apply Seeed rules to existing project
  kct init . --mfr jlcpcb                       Initialize in current directory
  kct init myproject --mfr jlcpcb --dry-run     Show what would be done

Available manufacturers: {", ".join(get_manufacturer_ids())}
Design types: {", ".join(design_types)}
""",
    )
    parser.add_argument(
        "project",
        help="Project name or path to .kicad_pro file (use '.' for current directory)",
    )
    parser.add_argument(
        "-m",
        "--mfr",
        required=True,
        metavar="MANUFACTURER",
        help="Manufacturer ID (jlcpcb, seeed, pcbway, oshpark)",
    )
    parser.add_argument(
        "-l",
        "--layers",
        type=int,
        default=2,
        help="Number of copper layers (default: 2)",
    )
    parser.add_argument(
        "-c",
        "--copper",
        type=float,
        default=1.0,
        help="Copper weight in oz (default: 1.0)",
    )
    parser.add_argument(
        "-t",
        "--design-type",
        choices=design_types,
        default=None,
        metavar="TYPE",
        help=f"Design type for netclass configuration ({', '.join(design_types)})",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be done without making changes",
    )
    parser.add_argument(
        "--format",
        choices=["text", "json"],
        default="text",
        help="Output format (default: text)",
    )

    args = parser.parse_args(argv)

    return init_project(
        target=args.project,
        manufacturer=args.mfr,
        layers=args.layers,
        copper=args.copper,
        design_type=args.design_type,
        dry_run=args.dry_run,
        output_format=args.format,
    )


if __name__ == "__main__":
    sys.exit(main())
