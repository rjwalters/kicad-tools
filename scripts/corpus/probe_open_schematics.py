def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="probe_open_schematics.py",
        description=(
            "Sample N random records from the bshada/open-schematics Hugging Face "
            "dataset, parse them with kicad_tools' own parsers, and emit a failure "
            "taxonomy report (JSON + human-readable). Local/opt-in: never run in CI."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Dataset: https://huggingface.co/datasets/bshada/open-schematics (CC-BY-4.0)\n"
            "Reports default to scripts/corpus/.cache/ (gitignored); sampled payloads\n"
            "are downloaded to a system temp dir that is removed on exit."
        ),
    )
    parser.add_argument("--n", type=int, default=50, help="records to sample (default: 50)")
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="RNG seed for reproducible sampling (default: random; the effective "
        "seed is recorded in the report so any run can be replayed)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help=f"report output directory (default: {DEFAULT_OUT_DIR.relative_to(REPO_ROOT)})",
    )
    parser.add_argument("--dataset", default=DEFAULT_DATASET, help="Hugging Face dataset id")
    parser.add_argument("--config", default="default", help="dataset config (default: default)")
    parser.add_argument("--split", default="train", help="dataset split (default: train)")
    parser.add_argument(
        "--kinds",
        choices=("both", "schematic", "pcb"),
        default="both",
        help="which payloads to parse per record (default: both)",
    )
    parser.add_argument(
        "--max-bytes",
        type=int,
        default=8_000_000,
        help="skip payloads larger than this many bytes (default: 8000000)",
    )
    parser.add_argument("--timeout", type=float, default=60.0, help="per-request timeout seconds")
    parser.add_argument("--retries", type=int, default=3, help="retries per HTTP request")
    parser.add_argument(
        "--keep-sources",
        choices=("none", "failures", "all"),
        default="failures",
        help="retain sampled payloads under <out>/sources/ for triage (default: failures)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="no network: sample in-repo KiCad files instead, exercising the same "
        "parse/classify/report path (useful offline or to smoke-test the script)",
    )
    parser.add_argument("--quiet", action="store_true", help="suppress per-record progress")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.n <= 0:
        print("error: --n must be positive", file=sys.stderr)
        return 2

    seed = args.seed if args.seed is not None else random.SystemRandom().randrange(2**32)
    rng = random.Random(seed)

    out_dir: Path = args.out.expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    retain_dir: Path | None = None
    if args.keep_sources != "none":
        retain_dir = out_dir / "sources"
        retain_dir.mkdir(parents=True, exist_ok=True)

    # Downloads land in a scratch dir OUTSIDE the repo, removed on exit.
    scratch_dir = Path(tempfile.mkdtemp(prefix="kct-corpus-probe-"))
    revision: str | None = None
    try:
        if args.dry_run:
            candidates = local_candidates()
            if not candidates:
                print("error: --dry-run found no in-repo KiCad files", file=sys.stderr)
                return 1
            chosen = rng.sample(candidates, min(args.n, len(candidates)))
            chosen.sort()
            sampled: list[int] | list[str] = [str(p.relative_to(REPO_ROOT)) for p in chosen]
            row_count = len(candidates)
            records = probe_local_records(args, chosen, scratch_dir, retain_dir, args.keep_sources)
        else:
            revision = dataset_revision(args.dataset, args.timeout, args.retries)
            row_count = dataset_row_count(
                args.dataset, args.config, args.split, args.timeout, args.retries
            )
            offsets = sorted(rng.sample(range(row_count), min(args.n, row_count)))
            sampled = offsets
            records = probe_hub_records(args, offsets, scratch_dir, retain_dir, args.keep_sources)
    except HubError as exc:
        print(f"error: {exc}", file=sys.stderr)
        print(
            "hint: re-run with --dry-run to exercise the parse/report path offline.",
            file=sys.stderr,
        )
        return 1
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130
    finally:
        shutil.rmtree(scratch_dir, ignore_errors=True)

    if not records:
        print("error: no records were sampled", file=sys.stderr)
        return 1

    report = build_report(args, seed, revision, row_count, sampled, records)
    summary = render_summary(report)

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    json_path = out_dir / f"probe-{stamp}.json"
    text_path = out_dir / f"probe-{stamp}.txt"
    json_path.write_text(json.dumps(report, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    text_path.write_text(summary + "\n", encoding="utf-8")

    print(summary)
    print(f"JSON report : {json_path}")
    print(f"text report : {text_path}")
    if retain_dir is not None:
        print(f"retained    : {retain_dir} (--keep-sources={args.keep_sources})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
