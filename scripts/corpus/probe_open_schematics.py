#!/usr/bin/env python3
"""Probe the ``bshada/open-schematics`` corpus through this repo's KiCad parsers.

Issue #4830 (deliverable 1) — a **local, opt-in** dev tool that answers one
question: *how does ``kicad_tools``' own s-expression parser hold up against
real-world KiCad files it did not author?*

Everything this repo measures today runs against the 9 in-repo boards, all of
them generated by ``kct``. The Hugging Face dataset
`bshada/open-schematics <https://huggingface.co/datasets/bshada/open-schematics>`_
(CC-BY-4.0, 87,931 records / ~317 GB) is a free real-world regression corpus:
each record carries a raw schematic source plus the paired PCB source(s) from a
human-completed design. This script samples N random records, runs each payload
through :meth:`kicad_tools.schema.Schematic.load` / :meth:`kicad_tools.schema.PCB.load`,
and emits a **failure taxonomy** — a JSON report for machine consumption and a
human-readable summary — so parser-hardening work can be prioritised by what
actually breaks, and how often.

Design constraints (from the issue; please preserve them):

* **Zero new default dependencies.** stdlib + ``requests`` only (``requests`` is
  already available via the ``dev`` and ``parts`` extras). The Hugging Face
  ``datasets`` library is deliberately *not* used and must not be added.
* **Opt-in / local only.** This script is never wired into a CI workflow and is
  never imported from anything under ``tests/`` — it does network I/O.
* **No corpus in the repo.** Sampled payloads are written to a scratch directory
  under the system temp dir (removed on exit); reports and any retained sources
  go to ``scripts/corpus/.cache/`` by default, which is gitignored. A run leaves
  ``git status`` clean.

Why the datasets-server ``/rows`` endpoint (and not ``/tree/main``)?
    The dataset is published as ~1,700 parquet shards under ``data/``, not as
    individual ``.kicad_sch`` / ``.kicad_pcb`` blobs, so listing the repo tree
    gives you no per-record granularity and the smallest shard is still hundreds
    of MB. The Hugging Face **datasets-server** HTTP API exposes the same
    dataset row-by-row (``/info`` for the row count, ``/rows`` for a window at a
    given offset) and returns the raw file contents as JSON strings. That is a
    plain HTTP API — no ``datasets`` dependency — and it lets us fetch exactly
    the N records we sampled instead of a shard's worth of neighbours.

Usage::

    # 50 random records (the default), reports under scripts/corpus/.cache/
    uv run python scripts/corpus/probe_open_schematics.py

    # small, reproducible sample — same --seed re-samples the same records
    uv run python scripts/corpus/probe_open_schematics.py --n 10 --seed 1234

    # no network: exercise the parse/report path against in-repo KiCad files
    uv run python scripts/corpus/probe_open_schematics.py --dry-run --n 20 --seed 7

Exit status is 0 whenever the probe ran (individual record failures are *data*,
not errors) and 1 only when nothing could be sampled at all.
"""

